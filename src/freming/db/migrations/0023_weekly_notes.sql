-- =====================================================================
-- 0023: 週次レポートの講評（LLM が書いた文章）
--
-- 数字の比較（考察）は機械的に出せるが、文章としての講評は書けない。
-- 週に1回だけ Claude に書かせて、ここに残す。
--
-- **画面を開くたびに呼ばない。** /report は何度も開く画面なので、
-- 開くたびにAPIを叩くと、見るだけで費用が出るうえ表示も遅くなる。
-- 生成は週1の定期実行（report-comment）だけが行い、画面は保存された
-- 文章を読むだけにする。
--
-- source は**そのとき渡した数字そのもの**。あとから「この講評は何を
-- 見て書かれたのか」を確かめられるようにするため。モデルが数字を
-- 取り違えていないかは、これと突き合わせれば分かる。
-- =====================================================================

CREATE TABLE IF NOT EXISTS weekly_notes (
  week_start TEXT PRIMARY KEY,   -- その週の月曜（現地時刻の日付）
  body       TEXT NOT NULL,      -- 講評の本文
  source     TEXT,               -- 渡した数字（検証用）
  model      TEXT,
  created_at TEXT
);
