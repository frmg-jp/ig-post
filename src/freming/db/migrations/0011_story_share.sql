-- 0011_story_share: ストーリーズへの手動追加を追いかける
-- =====================================================================
--
-- **ストーリーズは自動化しない**（2026-08-07 の判断）。
--
-- やりたかったのは「投稿をストーリーズに追加」の形、つまりタップすると
-- その投稿へ飛ぶカードだが、**Meta の API はこれを開けていない。**
-- リンク・メンション・アンケートといったスタンプ類は一切投稿できず、
-- ストーリーズはキャプションすら受け付けない（テキストを送っても無視
-- される）。他社ツールが対応していないのも同じ理由で、こちらの実装の
-- 問題ではない。
--
-- 非公式APIのライブラリなら可能だが、規約違反でアカウント停止の対象に
-- なり、アカウントのパスワードをサーバーに置くことになる。**投稿先の
-- アカウントごと失う可能性**と引き換えにする価値はないと判断した。
--
-- 代わりに、毎日1回まとめて手で上げる。人がやるのは
--   「投稿を開く → 紙飛行機 → ストーリーズに追加」の2タップだけ
-- にしたいので、必要なものをここに持つ。
--
--   permalink        … 投稿のURL。審査UIから開く／リンクスタンプに貼る
--   story_shared_at  … 追加済みの印。3件中どれが残っているかが分かる

ALTER TABLE posts ADD COLUMN permalink TEXT;
ALTER TABLE posts ADD COLUMN story_shared_at TEXT;
