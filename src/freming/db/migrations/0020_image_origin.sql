-- =====================================================================
-- 0020: 画像を「どのページから持ってきたか」を残す
--
-- これまで images.source_url は画像そのもののURLで、それがどのページに
-- 載っていたかは残していなかった。掲載ページは1つ（properties.source_url）
-- しか無い前提だったので、要らなかった。
--
-- **他のサイトから足す経路（images/discover.py）ができたので前提が崩れる。**
-- 1件の物件に、元の記事の写真と、画像検索で見つけた別記事の写真が混ざる。
-- 混ざったまま見分けが付かないと、審査で「この写真はどこの？」に答えられず、
-- クレジットも書けない。
--
-- NULL = 物件の掲載ページそのもの（従来どおり）。
-- 値が入っている = そのページから拾ってきた。
-- =====================================================================

ALTER TABLE images ADD COLUMN origin_url TEXT;

CREATE INDEX idx_images_origin ON images(property_id, origin_url);
