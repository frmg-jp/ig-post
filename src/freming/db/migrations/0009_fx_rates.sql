-- =====================================================================
-- 0009_fx_rates: 円換算レートの保管
-- =====================================================================
--
-- 審査UIの価格の並べ替えに使う。表示には使わない。
--
-- config.yaml ではなくDBに置く理由は、api_tokens と同じ:
-- **定期的に書き換わる値だから**。config.yaml は git で管理していて、
-- 自動更新するには毎回コミットとプッシュが要る。DBなら定期実行が行を
-- 1つ書き換えるだけで済み、審査UI（Render）と手元が同じ値を見る。
--
-- config.yaml の fx.jpy_per は残す。ここが空のとき（取得が一度も成功して
-- いない環境、テスト）の土台として使う。DBに値があればそちらが勝つ。

CREATE TABLE fx_rates (
  currency   TEXT PRIMARY KEY,   -- ISO 4217（USD / EUR / TWD ...）
  jpy_per    REAL NOT NULL,      -- 1通貨あたりの円
  fetched_at TEXT NOT NULL
);
